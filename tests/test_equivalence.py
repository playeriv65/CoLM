@pytest.mark.parametrize("name", list(TRAJECTORIES))
def test_training_trajectory(tmp_path, tokenizer, mixture_file, monkeypatch, name):
    golden = load("trajectories")[name]
    args = make_args(tmp_path, **TRAJECTORIES[name], **LEGACY)
    dropout = 0.2 if name.endswith("dropout") else 0.0
    trainer, model = build(args, tokenizer, mixture_file, lora_dropout=dropout)

    pools, trained, rng = [], [], []
    if args.coreset:
        gathered = pool_module.all_gather_object

        def record_pool(obj):
            out = gathered(obj)
            pools.append([int(e["colm_meta"]["indices"]) for chunk in out for e in chunk])
            return out

        monkeypatch.setattr(trainers, "all_gather_object", record_pool)
        sub_batches = trainer._sub_batches

        def record_sub_batches(examples, weights):
            out = sub_batches(examples, weights)
            for batch, weight in out:
                trained.append(
                    {
                        "step": trainer.state.global_step,
                        "indices": batch["colm_meta"]["indices"].tolist(),
                        "weight": None if args.efficient_mezo else weight,
                    }
                )
            return out

        trainer._sub_batches = record_sub_batches
        loss_fn = trainer.compute_loss

        def compute_loss(model, inputs, **kw):
            if not rng or rng[-1][0] != trainer.state.global_step:
                rng.append((trainer.state.global_step, torch.get_rng_state().clone()))
            return loss_fn(model, inputs, **kw)

        trainer.compute_loss = compute_loss
    trainer.train()

    logs = [
        {k: v for k, v in h.items() if k in ("step", "loss", "grad_norm", "learning_rate")}
        for h in trainer.state.log_history
        if "loss" in h
    ]
    assert len(logs) == len(golden["log"])
    for got, want in zip(logs, golden["log"], strict=True):
        assert got["step"] == want["step"]
        for key in ("loss", "grad_norm", "learning_rate"):
            assert got[key] == pytest.approx(want[key], rel=1e-9, abs=1e-12), (name, key)
    assert_same(lora_state(model), golden["lora"], f"{name}: LoRA weights", atol=1e-10)
    if args.coreset:
        assert len(pools) == len(golden["selections"])
        for pool, want in zip(pools, golden["selections"], strict=True):
            assert pool == want["pool"]
        assert len(trained) == len(golden["trained"])
        for got, want in zip(trained, golden["trained"], strict=True):
            assert got["step"] == want["step"] and got["indices"] == want["indices"], name
            assert got["weight"] == want["weight"], name
        for got, want in zip([s for _, s in rng], golden["rng_at_train_start"], strict=True):
            assert torch.equal(got, want), f"{name}: the RNG state after selection differs"
