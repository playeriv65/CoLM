LEGACY = dict(legacy=True)


def test_collated_batches(tokenizer, mixture_file):
    golden = load("data")
    dataset = get_training_dataset([mixture_file], tokenizer=tokenizer, max_seq_length=512)
    assert len(dataset) == golden["len"]
    assert dataset.all_data_sources == golden["all_data_sources"]
    collator = SupervisedCollator(tokenizer, legacy=True)
    for start, expected in zip((0, 4, 8, 13), golden["batches"], strict=True):
        batch = collator([dataset[i] for i in range(start, start + 4)])
        meta = batch["colm_meta"]
        assert_same(batch["input_ids"], expected["input_ids"])
        assert_same(batch["labels"], expected["labels"])
        assert_same(batch["attention_mask"].long(), expected["attention_mask"])
        assert meta["sources"].tolist() == expected["sources"]
        assert meta["indices"].tolist() == expected["indices"]
        assert meta["completion_lengths"].tolist() == expected["completion_lengths"]


@pytest.mark.parametrize("case", range(15))
def test_selection_stages(tmp_path, tokenizer, case):
    golden = load("select")[case]
    args = make_args(
        tmp_path,
        per_device_train_batch_size=1,
        gradient_accumulation_steps=32,
        small_batch_ratio=0.5,
        **golden["over"],
        **LEGACY,
    )
    model = model_fp64(tokenizer)
    params = zo_parameters(model, args.last_layers, args.last_layer_index)
    selector = CoresetSelector(
        args, NUM_LAYERS, weight_prior=lambda: torch.cat([p.flatten() for _, p in params])
    )
    for step in golden["steps"]:
        torch.manual_seed(step["step"])
        np.random.seed(step["step"])
        selection = selector(step["feats"].clone(), step["sources"], 16, step["step"])
        assert selection.indices == step["selected"], f"case {golden['over']} step {step['step']}"
        assert selection.weights == step["weights"]
    assert_same(selector.prev_m, golden["prev_m"])
    assert_same(selector.prev_v, golden["prev_v"])


def _pool_batches(trainer):
    return next(iter(trainer.get_train_dataloader()))["micro_batches"]


@pytest.mark.parametrize(
    "unit", ["rep", "mezo", "masked_grad", "completion_length", "length_loss_weighted"]
)
def test_features_of_each_unit(tmp_path, tokenizer, mixture_file, unit):
    golden = load("features")
    args = make_args(
        tmp_path,
        per_device_train_batch_size=1,
        gradient_accumulation_steps=4,
        data_selection_unit=unit,
        keep_sources="",
        **LEGACY,
    )
    trainer, model = build(args, tokenizer, mixture_file)
    features = []
    for batch in _pool_batches(trainer)[:3]:
        torch.manual_seed(5)
        model.train()
        if trainer.extractor.mode is not None:
            model.train(trainer.extractor.mode == "train")
        features.append(trainer._features(batch))
    for got, want in zip(features, golden[unit], strict=True):
        assert_same(got.reshape(want.shape).to(want.dtype), want, unit)
    assert_same(
        lora_state(model), golden[unit + "_param"], f"{unit}: parameters after the estimate"
    )


def test_efficient_features_and_losses(tmp_path, tokenizer, mixture_file):
    golden = load("features")
    args = make_args(
        tmp_path,
        per_device_train_batch_size=4,
        gradient_accumulation_steps=2,
        efficient_mezo=True,
        keep_sources="",
        **LEGACY,
    )
    trainer, model = build(args, tokenizer, mixture_file)
    batches = _pool_batches(trainer)
    model.eval()
    for batch, want in zip(batches, golden["efficient"], strict=True):
        assert_same(trainer.extractor.extract(batch), want)
    split = trainer.extractor.split
    with torch.no_grad():
        state = split.prefix(batches[0]["input_ids"], batches[0]["attention_mask"])
        loss = per_sample_loss(split.logits(state), batches[0]["labels"], legacy=True)
    assert_same(loss, golden["efficient_loss"])
    assert_same(lora_state(model), golden["efficient_param"], "parameters after the estimate")


